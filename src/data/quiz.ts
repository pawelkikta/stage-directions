/** Questions by id (for "review your mistakes"). Skips unknown ids. */
export function getQuestionsByIds(ids: string[]): Question[] {
  const map = new Map(QUIZ_BANK.map((qq) => [qq.id, qq]));
  return ids.map((id) => map.get(id)).filter((qq): qq is Question => !!qq);
}

/**
 * Draws `count` questions with a mix close to the blueprint weights. If a topic
 * has too few questions, it fills up from the rest of the pool. The result is shuffled.
 */
export function sampleWeighted(count: number): Question[] {
  const topics = Object.keys(EXAM_WEIGHTS) as ExamTopic[];
  const byTopic = new Map<ExamTopic, Question[]>();
  topics.forEach((t) => byTopic.set(t, shuffle(QUIZ_BANK.filter((x) => x.topic === t))));

  const picked: Question[] = [];
  topics.forEach((t) => {
    const target = Math.round((EXAM_WEIGHTS[t] / 100) * count);
    picked.push(...byTopic.get(t)!.slice(0, target));
  });

  // fill up or cut to count
  if (picked.length < count) {
    const used = new Set(picked.map((p) => p.id));
    const rest = shuffle(QUIZ_BANK.filter((x) => !used.has(x.id)));
    picked.push(...rest.slice(0, count - picked.length));
  }
  return shuffle(picked).slice(0, count);
}
