/* ===========================================================================
 * Quiz bank - questions tagged with the exam topic areas. The mix in a quiz
 * or exam follows the blueprint weights (Composition 23% and so on).
 * Facts checked (LIVERPS = 7 arcs).
 * ======================================================================== */
import type { ExamTopic } from "../core/types.ts";
import { EXAM_WEIGHTS } from "../core/types.ts";
import { shuffle } from "../core/shuffle.ts";

export interface Question {
  id: string;
  topic: ExamTopic;
  /** recall = a fact; scenario = reasoning; code = reading pxr code. */
  kind: "recall" | "scenario" | "code";
  /** Chapter for the "Chapter N →" link. */
  layerIndex?: number;
  q: string;
  /** pxr (Python) snippet shown above the question. */
  code?: string;
  options: string[];
  answer: number;
  explanation: string;
}

let qid = 0;
const q = (
  topic: ExamTopic,
  layerIndex: number,
  question: string,
  options: string[],
  answer: number,
  explanation: string,
): Question => ({
  id: `q${qid++}`,
  topic,
  kind: "recall",
  layerIndex,
  q: question,
  options,
  answer,
  explanation,
});

/** A scenario question (reasoning, not recall). */
const qs = (
  topic: ExamTopic,
  layerIndex: number,
  question: string,
  options: string[],
  answer: number,
  explanation: string,
): Question => ({
  id: `q${qid++}`,
  topic,
  kind: "scenario",
  layerIndex,
  q: question,
  options,
  answer,
  explanation,
});

/** A pxr code-reading question (snippet + "what does it do / return"). */
const qc = (
  topic: ExamTopic,
  layerIndex: number,
  code: string,
  question: string,
  options: string[],
  answer: number,
  explanation: string,
): Question => ({
  id: `q${qid++}`,
  topic,
  kind: "code",
  layerIndex,
  q: question,
  code,
  options,
  answer,
  explanation,
});

