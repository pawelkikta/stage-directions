/* ===========================================================================
 * Verifier for the Predict / Find-the-bug situations.
 *
 * Runs every situation (the base script, "try it" and "after the fix") in an
 * empty folder on real USD and writes the printed output, together with a hash
 * of the script, to src/data/sandbox.verified.ts. The app shows only these
 * outputs; when someone changes a situation and does not rerun this, the app
 * shows a warning instead of the output.
 *
 *   npm run verify:sandbox                   all situations
 *   npm run verify:sandbox -- p-traverse     only the given ones (the rest stays)
 *
 * USD: unpacked binaries with python/ and lib/python/pxr inside. Default
 * ~/Documents/usdview; set another path with USD_ROOT, another Python with
 * USD_PYTHON.
 * ======================================================================== */
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { delimiter, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { buildScript, scriptHash } from "../src/core/sandboxScript.ts";
import { SANDBOX, type SandboxEdit, type SandboxItem } from "../src/data/sandbox.ts";
import { SANDBOX_VERIFIED, type VerifiedRun } from "../src/data/sandbox.verified.ts";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "sandbox.verified.ts");

const usdRoot = process.env.USD_ROOT ?? join(homedir(), "Documents", "usdview");
const python =
  process.env.USD_PYTHON ??
  (process.platform === "win32" ? join(usdRoot, "python", "python.exe") : join(usdRoot, "python", "bin", "python3"));

if (!existsSync(python)) {
  console.error(`No Python with USD: ${python}\nSet USD_ROOT (the folder with the USD binaries) or USD_PYTHON.`);
  process.exit(1);
}

const env = {
  ...process.env,
  PYTHONPATH: join(usdRoot, "lib", "python"),
  PATH: [join(usdRoot, "lib"), join(usdRoot, "bin"), process.env.PATH ?? ""].join(delimiter),
  // The output must be the same on every console, whatever its code page.
  PYTHONIOENCODING: "utf-8",
};

function runPython(args: string[], cwd: string): string {
  const run = spawnSync(python, args, { cwd, env, encoding: "utf8" });
  if (run.status !== 0) {
    throw new Error(`Python exited with code ${run.status}\n${run.stderr}`);
  }
  return run.stdout.replace(/\r\n/g, "\n").trimEnd();
}

function usdVersion(): string {
  const text = runPython(["-c", "from pxr import Usd; v = Usd.GetVersion(); print(f'{v[1]}.{v[2]:02d}')"], tmpdir());
  return text.trim();
}

/** One script in a fresh folder, the way the user will run it. */
function verify(item: SandboxItem, edits: SandboxEdit[] = [], variant = ""): VerifiedRun {
  const script = buildScript(item, edits, variant);
  const dir = mkdtempSync(join(tmpdir(), "situation-"));
  try {
    const name = item.mode === "bug" ? "bug.py" : "situation.py";
    writeFileSync(join(dir, name), script, "utf8");
    return { output: runPython([name], dir), hash: scriptHash(script) };
  } catch (error) {
    throw new Error(`${item.id}${variant ? ` (${variant})` : ""}: ${(error as Error).message}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const only = new Set(process.argv.slice(2));
for (const id of only) {
  if (!SANDBOX.some((item) => item.id === id)) {
    console.error(`There is no situation "${id}".`);
    process.exit(1);
  }
}

const version = usdVersion();
console.log(`USD ${version} (${python})`);

const result: typeof SANDBOX_VERIFIED = {};
for (const item of SANDBOX) {
  if (only.size > 0 && !only.has(item.id)) {
    if (SANDBOX_VERIFIED[item.id]) {
      result[item.id] = SANDBOX_VERIFIED[item.id];
    }
    continue;
  }

  // The same variants and labels as in SandboxView, so the hashes match.
  const entry: (typeof SANDBOX_VERIFIED)[string] = { base: verify(item) };
  if (item.tryIt) {
    entry.tryIt = verify(item, item.tryIt.edits, item.tryIt.label);
  }
  if (item.fix) {
    entry.fixed = verify(item, item.fix, "after the fix");
  }
  result[item.id] = entry;

  console.log(`\n[${item.id}]`);
  for (const [kind, run] of Object.entries(entry)) {
    console.log(`  ${kind}: ${run.output.replace(/\n/g, "\n  " + " ".repeat(kind.length + 2))}`);
  }
}

const header = `/* Generated by the situation verifier (npm run verify:sandbox) - do not edit by hand.
 * Script output from USD ${version}; hash = hash of the script the output belongs to. */
export interface VerifiedRun {
  output: string;
  hash: string;
}

export const SANDBOX_VERIFIED: Record<string, { base: VerifiedRun; fixed?: VerifiedRun; tryIt?: VerifiedRun }> = `;

writeFileSync(OUT, header + JSON.stringify(result, null, 2) + ";\n", "utf8");
console.log(`\nWrote ${Object.keys(result).length} situations to ${OUT}`);
