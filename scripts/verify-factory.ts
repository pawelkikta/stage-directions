/* ===========================================================================
 * Verifier of the Drone Factory (the Drone Factory page).
 *
 * For each of the 9 steps it writes the factory files (src/core/factory/usd.ts)
 * to an empty folder, runs the check script from src/data/factory.ts and
 * scripts/factory_snapshot.py, and writes the result with a fingerprint of the
 * files to src/data/factory.verified.ts. After step 9 it also writes the
 * package public/factory/factory.usdz and a usdrecord render from the camera in USD.
 *
 *   npm run verify:factory
 * ======================================================================== */
import { spawnSync } from "node:child_process";
import { closeSync, copyFileSync, mkdirSync, mkdtempSync, openSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { stepHash } from "../src/core/factory/hash.ts";
import { FACTORY_STEPS as STEP_COUNT, factoryFiles } from "../src/core/factory/usd.ts";
import { FACTORY_STEPS } from "../src/data/factory.ts";
import { env, python, requirePython } from "./usd-env.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const OUT = join(ROOT, "src", "data", "factory.verified.ts");

requirePython();

/** Output as in a console: stdout and stderr together, without the USD "Warning: in" lines. */
function run(args: string[], cwd: string): { out: string; code: number | null } {
  const logDir = mkdtempSync(join(tmpdir(), "factory-log-"));
  const log = join(logDir, "out.txt");
  const fd = openSync(log, "w");
  try {
    const r = spawnSync(python, args, { cwd, env, stdio: ["ignore", fd, fd] });
    closeSync(fd);
    const out = readFileSync(log, "utf8")
      .replace(/\r\n/g, "\n")
      .split("\n")
      .filter((l) => !l.startsWith("Warning: in "))
      .map((l) => l.trimEnd())
      .join("\n")
      .trimEnd();
    return { out, code: r.status };
  } finally {
    rmSync(logDir, { recursive: true, force: true });
  }
}

const results: unknown[] = [];
let failed = false;

for (let step = 1; step <= STEP_COUNT; step++) {
  const files = factoryFiles(step);
  const check = FACTORY_STEPS[step - 1].check;
  const dir = mkdtempSync(join(tmpdir(), `factory-step${step}-`));
  const scripts = mkdtempSync(join(tmpdir(), "factory-script-"));
  try {
    for (const [name, text] of Object.entries(files)) {
      mkdirSync(dirname(join(dir, name)), { recursive: true });
      writeFileSync(join(dir, name), text, "utf8");
    }
    writeFileSync(join(scripts, "check.py"), check, "utf8");
    const checked = run([join(scripts, "check.py")], dir);
    const snapFile = join(scripts, "snapshot.json");
    const snap = run([join(HERE, "factory_snapshot.py"), dir, snapFile], dir);

    console.log(`\n[step ${step}] ${FACTORY_STEPS[step - 1].title}`);
    console.log(checked.out.replace(/^/gm, "  "));
    if (checked.code !== 0 || snap.code !== 0) {
      failed = true;
      console.log(`  ERROR: check ${checked.code}, snapshot ${snap.code}\n${snap.out}`);
      continue;
    }

    const snapshot = JSON.parse(readFileSync(snapFile, "utf8"));
    results.push({ hash: stepHash(files, check), output: checked.out, snapshot });

    if (step === STEP_COUNT) {
      mkdirSync(join(ROOT, "public", "factory"), { recursive: true });
      copyFileSync(join(dir, "factory.usdz"), join(ROOT, "public", "factory", "factory.usdz"));
      const png = join(ROOT, "public", "renders", "factory-usdrecord.png");
      const render = spawnSync(
        "cmd.exe",
        ["/d", "/s", "/c", `"usdrecord --camera /Factory/Camera --imageWidth 960 factory.usda "${png}""`],
        { cwd: dir, env, encoding: "utf8", windowsVerbatimArguments: true },
      );
      console.log(`  package: public/factory/factory.usdz | usdrecord render: code ${render.status}`);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
    rmSync(scripts, { recursive: true, force: true });
  }
}

if (failed) {
  console.error("\nNot all steps passed - the results file was not written.");
  process.exit(1);
}

const header = `/* Generated by npm run verify:factory - do not edit by hand.
 * For each step: the output of the check script and a scene snapshot from USD 25.08;
 * hash = fingerprint of the step files and the script that the result belongs to. */
import type { FactorySnapshot } from "../core/factory/snapshot.ts";

export interface FactoryVerified {
  hash: string;
  output: string;
  snapshot: FactorySnapshot;
}

export const FACTORY_VERIFIED: FactoryVerified[] = `;
writeFileSync(OUT, header + JSON.stringify(results) + ";\n", "utf8");
console.log(`\nWrote ${results.length} steps to ${OUT}`);
